"""artifacts.py — compile a validated `BrandKit` into its static, on-disk artifacts.

Split out of `compile.py` purely to keep files small (AGENTS.md: no file over ~400
lines) — `compile.py` owns the generation-facing builders (`still_prompt`/
`motion_prompt`/`animation_brief`/`writer_context`); this module owns everything written
into a compiled kit's out dir: `brand.css`, `design.md`, `captions.json`,
`qa_checklist.md`, `kit.json`, and the driver (`compile_kit`) that writes them all plus
`writer_context.json` and the logo assets.
"""
from __future__ import annotations

import json
from pathlib import Path

from .compile import compiled_ui_shades, writer_context
from .look import Look
from .schema import BrandKit


# ---- brand.css --------------------------------------------------------------------

def compile_css(kit: BrandKit) -> str:
    motion = kit.house["motion_design"]
    safe = kit.house["safe_areas"]
    shades = compiled_ui_shades(kit)
    lines = [
        f"/* {kit.name} brand.css — generated by brandkit.compile, do not hand-edit.",
        f"   Source: brand.yaml v{kit.version}, kit hash {kit.kit_hash()[:12]} */",
        "",
        ":root {",
    ]
    for role, c in kit.core_colours.items():
        if c.status == "filled":
            lines.append(f"  --{role.replace('_', '-')}: {c.hex};")
    for key, hexv in shades.items():
        lines.append(f"  --{key.replace('_', '-')}: {hexv};")
    for key, v in kit.animation_css_vars.items():
        if v.status == "filled" and key not in shades:
            lines.append(f"  --{key.replace('_', '-')}: {v.value};")
    for key, t in kit.core_typography.items():
        if t.status == "filled":
            fallback = "monospace" if key == "mono" else "sans-serif"
            lines.append(f'  --font-{key}: "{t.family}", {fallback};')
    for name, dur in motion["durations"].items():
        lines.append(f"  --duration-{name}: {dur}s;")
    lines.append(f"  --ease: {motion['ease']};")
    for logo in kit.core_logos.values():
        if logo.status != "filled":
            continue
        for aspect, placement in logo.placements.items():
            suffix = aspect.replace(":", "x")
            lines.append(f"  --logo-{logo.variant}-h-{suffix}: {placement.height_px}px;")
    for aspect, box in safe.items():
        if aspect in ("16:9", "9:16"):
            suffix = aspect.replace(":", "x")
            lines.append(f"  --safe-title-{suffix}: {box['title_safe']};")
            lines.append(f"  --safe-action-{suffix}: {box['action_safe']};")
    lines.append("}")
    lines.append("")
    return "\n".join(lines) + "\n"


# ---- design.md (hyperframes-creative schema) ----------------------------------------

def compile_design_md(kit: BrandKit) -> str:
    fm = {
        "name": f"{kit.core_identity_name.text or kit.name} — brand kit",
        "version": kit.version,
        "colorRatio": kit.animation_colour_ratio.text or kit.house["color_ratio"]["default"],
        "colors": {k: c.hex for k, c in kit.core_colours.items() if c.status == "filled"},
        "typography": {
            k: {"fontFamily": t.family, "source": t.source}
            for k, t in kit.core_typography.items() if t.status == "filled"
        },
        "logos": {
            k: {
                "file": l.file, "clearSpace": l.clear_space, "minSizePx": l.min_size_px,
                "placements": {a: {"position": p.position, "insetPx": p.inset_px, "heightPx": p.height_px}
                               for a, p in l.placements.items()},
            }
            for k, l in kit.core_logos.items() if l.status == "filled"
        },
        "motion": kit.house["motion_design"],
    }
    import yaml as _yaml
    frontmatter = _yaml.safe_dump(fm, sort_keys=False, default_flow_style=False)

    body_lines = [
        "",
        f"# {kit.core_identity_name.text or kit.name} — brand kit",
        "",
        "## Personality",
        "",
        kit.core_personality_voice.text.strip() if kit.core_personality_voice.status == "filled" else "(core.personality.voice pending)",
        "",
        "## Names",
        "",
        f"Official: {', '.join(kit.core_names_official.items) or '(none)'}",
        "",
        f"Products: {', '.join(kit.core_names_products.items) or '(none)'}",
        "",
    ]
    return "---\n" + frontmatter + "---\n" + "\n".join(body_lines)


# ---- captions.json (keys animate-captions/build_captions.py reads) ------------------

def compile_captions(kit: BrandKit, look: Look | None = None) -> dict:
    cap = kit.animation_caption_style
    font_role = cap.font_role
    palette = dict(cap.palette)
    band, max_words, font_scale = cap.band, cap.max_words, cap.font_scale
    if look and look.caption_style:
        override = look.caption_style
        font_role = override.get("font_role", font_role)
        palette = {**palette, **override.get("palette", {})}
        band = override.get("band", band)
        max_words = override.get("max_words", max_words)
        font_scale = override.get("font_scale", font_scale)
    font = kit.core_typography[font_role]
    return {
        "fonts": {"body": font.family},
        "palette_dark": {"brand": palette["dark"]},
        "palette_light": {"brand": palette["light"]},
        "band": band,
        "max_words": max_words,
        "font_scale": font_scale,
    }


# ---- qa_checklist.md (house + kit) ---------------------------------------------------

def compile_qa_checklist(kit: BrandKit) -> str:
    lines = [f"# {kit.core_identity_name.text or kit.name} — QA checklist", "", "## House (every client)", ""]
    for i, item in enumerate(kit.house["qa_checklist"]["items"], 1):
        lines.append(f"{i}. {item}")
    if kit.qa_checklist_extra:
        lines += ["", f"## {kit.core_identity_name.text or kit.name} — additional", ""]
        for i, item in enumerate(kit.qa_checklist_extra, 1):
            lines.append(f"{i}. {item}")
    return "\n".join(lines) + "\n"


# ---- kit.json -------------------------------------------------------------------------

def compile_kit_json(kit: BrandKit) -> dict:
    return {"name": kit.name, "version": kit.version, "hash": kit.kit_hash()}


# ---- driver -----------------------------------------------------------------------------

def compile_kit(kit: BrandKit, out_dir: str | Path, look: Look | None = None) -> dict[str, Path]:
    """Write every compiled artifact into `out_dir`. Returns {artifact_name: path}."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    written: dict[str, Path] = {}

    css_path = out_dir / "brand.css"
    css_path.write_text(compile_css(kit), encoding="utf-8")
    written["brand.css"] = css_path

    design_path = out_dir / "design.md"
    design_path.write_text(compile_design_md(kit), encoding="utf-8")
    written["design.md"] = design_path

    captions_path = out_dir / "captions.json"
    captions_path.write_text(json.dumps(compile_captions(kit, look), indent=2) + "\n", encoding="utf-8")
    written["captions.json"] = captions_path

    qa_path = out_dir / "qa_checklist.md"
    qa_path.write_text(compile_qa_checklist(kit), encoding="utf-8")
    written["qa_checklist.md"] = qa_path

    kit_json_path = out_dir / "kit.json"
    kit_json_path.write_text(json.dumps(compile_kit_json(kit), indent=2) + "\n", encoding="utf-8")
    written["kit.json"] = kit_json_path

    writer_context_path = out_dir / "writer_context.json"
    writer_context_path.write_text(json.dumps(writer_context(kit, look), indent=2) + "\n", encoding="utf-8")
    written["writer_context.json"] = writer_context_path

    assets_dir = out_dir / "assets"
    assets_dir.mkdir(exist_ok=True)
    for logo in kit.core_logos.values():
        if not logo.file:
            continue
        src = kit.path / logo.file
        dst = assets_dir / Path(logo.file).name
        dst.write_bytes(src.read_bytes())
        written[f"assets/{dst.name}"] = dst

    return written
